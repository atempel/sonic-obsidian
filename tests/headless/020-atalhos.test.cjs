// Spec 020: tecla `?` abre o painel de atalhos, o filtro funciona e Esc fecha.
const H = require('./harness.cjs')
const srv = H.serve(5201)
const R = H.createResults('020-atalhos'); const ok = R.ok
;(async () => {
  const b = await H.launch()
  const page = await b.newPage({ viewport: { width: 1280, height: 800 } }); R.attach(page)
  const errs = []; page.on('pageerror', e => errs.push(String(e)))
  await H.mockSo(page); await H.mockAudio(page)
  await page.goto('http://localhost:5201/')
  await page.waitForSelector('.now-title[title]:not([title=""])', { timeout: 30000 })
  await page.waitForTimeout(1000)
  await page.mouse.move(640, 400)
  await page.keyboard.press('Shift+Slash'); await page.waitForTimeout(400)
  ok('1 "?" abre o painel de atalhos', await page.isVisible('.kpanel'))
  await page.fill('input[aria-label="Filtrar atalhos"]', 'segurar'); await page.waitForTimeout(200)
  const txt = await page.$eval('.kpanel', e => e.innerText)
  ok('2 filtrar por "segurar" mostra "Segurar visual"', txt.includes('Segurar visual'), txt.slice(0, 120).replace(/\n/g, ' | '))
  await page.keyboard.press('Escape'); await page.waitForTimeout(400)
  ok('3 Esc fecha', !(await page.isVisible('.kpanel')))
  ok('sem erros na página', errs.length === 0, JSON.stringify(errs.slice(0, 5)))
  const code = await R.finish()
  await b.close(); srv.close(); process.exit(code)
})().catch(e => { R.dump(); console.error(e); process.exit(1) })
