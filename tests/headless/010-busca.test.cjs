// Spec 010: Ctrl+K abre a busca; digitar parte do nome do preset atual lista um resultado; "modo limpo" mostra o comando.
const H = require('./harness.cjs')
const srv = H.serve(5203)
const R = H.createResults('010-busca'); const ok = R.ok
;(async () => {
  const b = await H.launch()
  const page = await b.newPage({ viewport: { width: 1280, height: 800 } }); R.attach(page)
  const errs = []; page.on('pageerror', e => errs.push(String(e)))
  await H.mockSo(page); await H.mockAudio(page)
  await page.goto('http://localhost:5203/')
  await page.waitForSelector('.now-title[title]:not([title=""])', { timeout: 30000 })
  await page.waitForTimeout(1000)
  const cur = await page.$eval('.now-title', e => e.getAttribute('title'))
  await page.mouse.move(640, 400)
  await page.keyboard.press('Control+KeyK'); await page.waitForTimeout(500)
  ok('1 Ctrl+K abre a busca', await page.isVisible('.palette'))
  const part = cur.slice(0, 4)
  const input = '.palette input[aria-label="Buscar preset ou autor"]'
  await page.fill(input, part); await page.waitForTimeout(400)
  const n = await page.$$eval('.palette .prow:not(.cmd)', es => es.length)
  ok('2 digitar parte do nome lista resultado', n >= 1, `"${part}" de "${cur}" → ${n}`)
  await page.fill(input, 'modo limpo'); await page.waitForTimeout(400)
  const cmds = await page.$$eval('.palette .prow.cmd .r-title', es => es.map(e => e.textContent))
  ok('3 "modo limpo" mostra o comando', cmds.some(t => /modo limpo/i.test(t)), JSON.stringify(cmds))
  await page.keyboard.press('Escape'); await page.waitForTimeout(400)
  ok('4 Esc fecha', await page.waitForSelector('.palette', { state: 'hidden', timeout: 3000 }).then(() => true, () => false) && !(await page.evaluate(() => document.body.classList.contains('palette-open'))))
  ok('sem erros na página', errs.length === 0, JSON.stringify(errs.slice(0, 5)))
  const code = await R.finish()
  await b.close(); srv.close(); process.exit(code)
})().catch(e => { R.dump(); console.error(e); process.exit(1) })
